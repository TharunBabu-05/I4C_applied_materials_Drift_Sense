# Phase-2 Dataset
# =============================================================================
class Phase2Dataset(Dataset):
    """
    Loads Phase-2 pairs from generate_phase2_dataset.py output format.

    For found=1 pairs (Sets A, B, D):
        - reference : the clean 100×100 reference crop
        - positive  : a crop extracted from search.png at GT (x, y, scale)
        - negative  : a random non-GT crop from a *different* pair or an absent pair

    For found=0 pairs (Set C — absent):
        - Used ONLY as negatives in triplets. Not used as anchors.
    """

    def __init__(self, data_dir: str, img_size: int = 100,
                 include_set_d: bool = True):
        self.img_size = img_size
        self.present_samples = []   # anchor+positive pairs (found=1)
        self.absent_samples  = []   # negatives pool (found=0)

        data_dir = Path(data_dir)
        pair_dirs = sorted(data_dir.glob("pair_*"))

        for pair_dir in pair_dirs:
            gt_path  = pair_dir / "groundtruth.json"
            ref_path = pair_dir / "reference.png"
            srch_path= pair_dir / "search.png"
            if not (gt_path.exists() and ref_path.exists() and srch_path.exists()):
                continue
            with open(gt_path) as f:
                gt = json.load(f)

            found = int(gt.get("found", 1))
            set_name = gt.get("set", "Set A")

            if not include_set_d and set_name == "Set D":
                continue

            sample = {
                "ref":   str(ref_path),
                "srch":  str(srch_path),
                "gt_x":  float(gt.get("target_x", 500.0)),
                "gt_y":  float(gt.get("target_y", 500.0)),
                "scale": float(gt.get("scale", 10.0)),
                "theta": float(gt.get("theta", 0.0)),
                "found": found,
                "set":   set_name,
            }

            if found == 1:
                self.present_samples.append(sample)
            else:
                self.absent_samples.append(sample)

        print(f"[Phase2Dataset] Present: {len(self.present_samples)} | "
              f"Absent (neg pool): {len(self.absent_samples)}")

    def _load_gray(self, path: str) -> np.ndarray:
        """Load and normalize a grayscale or BGR image to float32 [0,1]."""
        img = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
        if img is None:
            img = np.zeros((self.img_size, self.img_size), dtype=np.uint8)
        img = cv2.resize(img, (self.img_size, self.img_size), interpolation=cv2.INTER_AREA)
        return img.astype(np.float32) / 255.0

    def _extract_positive_crop(self, srch_path: str, gt_x: float, gt_y: float,
                                scale: float, theta: float) -> np.ndarray:
        """
        Crop the positive patch from the search image at GT location.
        The crop size is determined by scale (scale/10 × nominal 100px).
        The crop is resized back to img_size × img_size for the encoder.
        """
        srch = cv2.imread(srch_path, cv2.IMREAD_GRAYSCALE)
        if srch is None:
            return np.zeros((self.img_size, self.img_size), dtype=np.float32)

        h, w = srch.shape
        cx, cy = int(round(gt_x)), int(round(gt_y))

        # The positive crop should be the same size as the reference (100×100)
        # regardless of scale, because the search image has been globally transformed.
        half = self.img_size // 2
        x0, y0 = max(0, cx - half), max(0, cy - half)
        x1, y1 = min(w, cx + half), min(h, cy + half)
        crop = srch[y0:y1, x0:x1]

        # Pad if near boundary
        pad_t = max(0, half - (cy - 0))
        pad_b = max(0, (cy + half) - h)
        pad_l = max(0, half - (cx - 0))
        pad_r = max(0, (cx + half) - w)
        if any([pad_t, pad_b, pad_l, pad_r]):
            crop = np.pad(crop, ((pad_t, pad_b), (pad_l, pad_r)), mode='reflect')

        # Resize to standard size
        if crop.shape != (self.img_size, self.img_size):
            crop = cv2.resize(crop, (self.img_size, self.img_size), interpolation=cv2.INTER_AREA)

        # Undo rotation so the patch is aligned with the reference
        if abs(theta) > 0.5:
            M = cv2.getRotationMatrix2D((self.img_size / 2, self.img_size / 2), -theta, 1.0)
            crop = cv2.warpAffine(crop, M, (self.img_size, self.img_size),
                                  flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REPLICATE)

        return crop.astype(np.float32) / 255.0

    def _get_negative(self, anchor_idx: int) -> np.ndarray:
        """
        Return a hard negative: either from the absent pool (Set C)
        or a random different present-pair's positive crop.
        50% chance of each, to balance the training signal.
        """
        if self.absent_samples and random.random() < 0.5:
            # Absent pair: just use the reference (wrong architecture)
            neg_s = random.choice(self.absent_samples)
            return self._load_gray(neg_s["ref"])
        else:
            # Hard negative: a positive crop from a different present sample
            neg_idx = random.randint(0, len(self.present_samples) - 1)
            while neg_idx == anchor_idx:
                neg_idx = random.randint(0, len(self.present_samples) - 1)
            neg_s = self.present_samples[neg_idx]
            return self._extract_positive_crop(
                neg_s["srch"], neg_s["gt_x"], neg_s["gt_y"],
                neg_s["scale"], neg_s["theta"]
            )

    def __len__(self):
        return len(self.present_samples)

    def __getitem__(self, idx):
        s = self.present_samples[idx]

        ref = self._load_gray(s["ref"])
        pos = self._extract_positive_crop(s["srch"], s["gt_x"], s["gt_y"],
                                          s["scale"], s["theta"])
        neg = self._get_negative(idx)

        # Normalise scale and theta for regression heads
        # scale ∈ [8, 12] → normalised to [0, 1]
        scale_norm = (s["scale"] - 8.0) / 4.0
        # theta ∈ [-5, 5] → normalised to [0, 1]
        theta_norm = (s["theta"] + 5.0) / 10.0

        return {
            "reference": torch.tensor(ref).unsqueeze(0),    # [1, H, W]
            "positive":  torch.tensor(pos).unsqueeze(0),    # [1, H, W]
            "negative":  torch.tensor(neg).unsqueeze(0),    # [1, H, W]
            "scale":     torch.tensor([scale_norm], dtype=torch.float32),
            "theta":     torch.tensor([theta_norm], dtype=torch.float32),
            "found":     torch.tensor([float(s["found"])], dtype=torch.float32),
        }


# =============================================================================
# SEM Augmentation
# =============================================================================
class SEMAugment:
    """
    GPU-compatible SEM noise augmentation.
    Mirrors Phase-2 degradation model so the encoder learns
    to be invariant to the same corruptions.
    """
    def __init__(self, p: float = 0.7):
        self.p = p

    def __call__(self, x: torch.Tensor) -> torch.Tensor:
        if random.random() > self.p:
            return x

        # Poisson shot noise
        if random.random() < 0.6:
            sc = random.uniform(0.5, 1.5)
            x = torch.clamp(
                torch.poisson(torch.clamp(x * 255.0 * sc, min=0)) / (255.0 * sc), 0, 1
            )
        # Gaussian read noise
        if random.random() < 0.6:
            x = torch.clamp(x + torch.randn_like(x) * random.uniform(0.01, 0.06), 0, 1)

        # Brightness / contrast jitter
        if random.random() < 0.5:
            gain = 1.0 + random.uniform(-0.15, 0.15)
            bias = random.uniform(-0.08, 0.08)
            x = torch.clamp(x * gain + bias, 0, 1)

        # Charge-drift gradient (direction changes per call)
        if random.random() < 0.3:
            h = x.shape[-2]
            grad = torch.linspace(-0.05, 0.05, h, device=x.device).view(1, 1, h, 1)
            x = torch.clamp(x + grad * random.uniform(0.5, 1.5), 0, 1)

        return x


# =============================================================================
# Metrics
# =============================================================================
@torch.no_grad()
def triplet_accuracy(ref_emb, pos_emb, neg_emb):
    """Fraction of samples where positive is closer to anchor than negative."""
    d_pos = (ref_emb - pos_emb).pow(2).sum(dim=1)
    d_neg = (ref_emb - neg_emb).pow(2).sum(dim=1)
    return (d_pos < d_neg).float().mean().item()


# =============================================================================
# LR Schedule: linear warmup + cosine decay
# =============================================================================
def get_scheduler(optimizer, warmup_epochs: int, total_epochs: int):
    def lr_lambda(epoch):
        if epoch < warmup_epochs:
            return (epoch + 1) / max(1, warmup_epochs)
        progress = (epoch - warmup_epochs) / max(1, total_epochs - warmup_epochs)
        return 0.5 * (1.0 + np.cos(np.pi * progress))
    return optim.lr_scheduler.LambdaLR(optimizer, lr_lambda)


# =============================================================================
# Training epoch
# =============================================================================
def run_epoch(model, loader, triplet_criterion, optimizer, scaler,
              device, augment, train: bool,
              lambda_scale: float = 0.3, lambda_rot: float = 0.1,
              grad_clip: float = 5.0, desc: str = ""):

    model.train() if train else model.eval()
    total_loss = total_acc = 0.0
    n = 0

    mse = nn.MSELoss()
    pbar = tqdm(loader, desc=desc, leave=False, dynamic_ncols=True)
    ctx = torch.enable_grad() if train else torch.no_grad()

    with ctx:
        for batch in pbar:
            ref   = batch["reference"].to(device, non_blocking=True)
            pos   = batch["positive"].to(device, non_blocking=True)
            neg   = batch["negative"].to(device, non_blocking=True)
            scale = batch["scale"].to(device, non_blocking=True)
            theta = batch["theta"].to(device, non_blocking=True)

            if train and augment:
                ref = augment(ref)
                pos = augment(pos)
                neg = augment(neg)

            if train:
                optimizer.zero_grad(set_to_none=True)

            amp_ctx = torch.autocast(device_type=device.type,
                                     enabled=(scaler is not None and device.type == "cuda"))
            with amp_ctx:
                ref_emb = model.encoder(ref)
                pos_emb = model.encoder(pos)
                neg_emb = model.encoder(neg)

                # 1. Triplet loss — core siamese objective
                loss_triplet = triplet_criterion(ref_emb, pos_emb, neg_emb)
                loss = loss_triplet

                # 2 & 3. Scale and Rotation regression
                if hasattr(model, "predict_pose") and (lambda_scale > 0 or lambda_rot > 0):
                    scale_pred, theta_pred = model.predict_pose(ref_emb, pos_emb)
                    
                    # Note: scale and theta in dataset are normalized to [0,1]. 
                    # But model.predict_pose returns actual scale [8, 12] and theta [-5, 5].
                    # Let's normalize the predictions back to [0, 1] for MSE loss to be stable, 
                    # OR we can scale the GT to actual values.
                    # GT normalization in dataset:
                    # scale_norm = (s["scale"] - 8.0) / 4.0
                    # theta_norm = (s["theta"] + 5.0) / 10.0
                    
                    scale_pred_norm = (scale_pred - 8.0) / 4.0
                    theta_pred_norm = (theta_pred + 5.0) / 10.0
                    
                    if lambda_scale > 0:
                        # scale has shape [B, 1], scale_pred_norm has shape [B]
                        loss = loss + lambda_scale * mse(scale_pred_norm, scale.squeeze(1))
                    if lambda_rot > 0:
                        loss = loss + lambda_rot * mse(theta_pred_norm, theta.squeeze(1))

            acc = triplet_accuracy(ref_emb.detach(), pos_emb.detach(), neg_emb.detach())

            if train:
                if scaler is not None:
                    scaler.scale(loss).backward()
                    scaler.unscale_(optimizer)
                    nn.utils.clip_grad_norm_(model.parameters(), grad_clip)
                    scaler.step(optimizer)
                    scaler.update()
                else:
                    loss.backward()
                    nn.utils.clip_grad_norm_(model.parameters(), grad_clip)
                    optimizer.step()

            bs = ref.size(0)
            total_loss += loss.item() * bs
            total_acc  += acc * bs
            n += bs
            pbar.set_postfix({"loss": f"{loss.item():.4f}", "acc": f"{acc:.3f}"})

    return total_loss / max(n, 1), total_acc / max(n, 1)


# =============================================================================
# Main training function
# =============================================================================
def train(args):
    set_seed(args.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device : {device}")
    print(f"Data   : {args.data_dir}")

    # ── Dataset ───────────────────────────────────────────────────────────────
    full_ds = Phase2Dataset(args.data_dir, include_set_d=args.include_set_d)
    n_val   = max(1, int(len(full_ds) * args.val_split))
    n_train = len(full_ds) - n_val
    train_ds, val_ds = random_split(
        full_ds, [n_train, n_val],
        generator=torch.Generator().manual_seed(args.seed)
    )
    print(f"Train  : {len(train_ds)} samples  |  Val: {len(val_ds)} samples")

    train_loader = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True,
                              num_workers=args.num_workers,
                              pin_memory=(device.type == "cuda"),
                              drop_last=True)
    val_loader = DataLoader(val_ds, batch_size=args.batch_size, shuffle=False,
                            num_workers=args.num_workers,
                            pin_memory=(device.type == "cuda"))

    # ── Model ─────────────────────────────────────────────────────────────────
    model = PyramidSiameseNetwork(
        embedding_dim=args.embedding_dim,
        encoder_type="resnet"           # 4-layer custom ResNet
    ).to(device)

    if args.resume and os.path.exists(args.resume):
        state = torch.load(args.resume, map_location=device)
        missing, unexpected = model.load_state_dict(state, strict=False)
        print(f"Loaded weights from {args.resume}")
        if missing:    print(f"  Missing keys  : {missing}")
        if unexpected: print(f"  Unexpected keys: {unexpected}")
    else:
        print("[WARNING] No checkpoint found — training from scratch!")

    # ── Encoder freeze for first N epochs (avoid catastrophic forgetting) ────
    def set_encoder_trainable(trainable: bool):
        for p in model.encoder.parameters():
            p.requires_grad = trainable

    # ── Loss & optimizer ──────────────────────────────────────────────────────
    triplet_criterion = nn.TripletMarginLoss(margin=args.margin, p=2)

    def make_optimizer(encoder_lr_scale: float):
        """Differential LR: encoder gets encoder_lr_scale × base lr."""
        encoder_params = list(model.encoder.parameters())
        encoder_ids = {id(p) for p in encoder_params}
        other_params = [p for p in model.parameters() if id(p) not in encoder_ids]
        param_groups = [
            {"params": encoder_params, "lr": args.lr * encoder_lr_scale},
            {"params": other_params,   "lr": args.lr},
        ]
        return optim.AdamW(param_groups, weight_decay=args.weight_decay)

    optimizer = make_optimizer(encoder_lr_scale=0.1)  # start with frozen-like LR
    scheduler = get_scheduler(optimizer, args.warmup_epochs, args.epochs)
    scaler    = (torch.cuda.amp.GradScaler()
                 if device.type == "cuda" and args.amp else None)
    augment   = SEMAugment(p=args.aug_prob) if args.augment else None

    # ── Checkpoint dir ────────────────────────────────────────────────────────
    os.makedirs(args.checkpoint_dir, exist_ok=True)
    with open(os.path.join(args.checkpoint_dir, "config.json"), "w") as f:
        json.dump(vars(args), f, indent=2)

    best_val_acc = -1.0
    epochs_no_improve = 0
    history = []

    print(f"\n{'='*65}")
    print(f"  Phase-2 Training — 4-Layer ResNet + Siamese")
    print(f"  Encoder  : 4-layer custom ResNet (PyramidSiameseNetwork)")
    print(f"  Loss     : Triplet (margin={args.margin}) + Scale×{args.lambda_scale} + Rot×{args.lambda_rot}")
    print(f"  Freeze encoder for first {args.freeze_encoder_epochs} epochs")
    print(f"{'='*65}\n")

    for epoch in range(1, args.epochs + 1):
        t0 = time.time()

        # Differential LR: encoder gets 10x lower LR for first N freeze epochs,
        # then full LR. This avoids catastrophic forgetting without breaking backward().
        if epoch == 1:
            print(f"  [Encoder: SLOW LR (×0.1) for first {args.freeze_encoder_epochs} epochs]")
        elif epoch == args.freeze_encoder_epochs + 1:
            optimizer = make_optimizer(encoder_lr_scale=1.0)  # full LR for all
            scheduler = get_scheduler(optimizer, args.warmup_epochs, args.epochs)
            print(f"  [Encoder: FULL LR — encoder unfrozen at epoch {epoch}]")

        train_loss, train_acc = run_epoch(
            model, train_loader, triplet_criterion, optimizer, scaler,
            device, augment, train=True,
            lambda_scale=args.lambda_scale, lambda_rot=args.lambda_rot,
            grad_clip=args.grad_clip,
            desc=f"Ep {epoch:3d}/{args.epochs} [Train]"
        )
        val_loss, val_acc = run_epoch(
            model, val_loader, triplet_criterion, optimizer, scaler,
            device, None, train=False,
            lambda_scale=args.lambda_scale, lambda_rot=args.lambda_rot,
            grad_clip=args.grad_clip,
            desc=f"Ep {epoch:3d}/{args.epochs} [Val  ]"
        )

        scheduler.step()
        dt = time.time() - t0
        lr_now = optimizer.param_groups[0]["lr"]

        print(f"Epoch {epoch:3d}/{args.epochs} | lr={lr_now:.2e} | "
              f"train_loss={train_loss:.4f} acc={train_acc:.3f} | "
              f"val_loss={val_loss:.4f} acc={val_acc:.3f} | {dt:.1f}s")

        history.append({
            "epoch": epoch,
            "train_loss": round(train_loss, 5),
            "train_acc":  round(train_acc, 4),
            "val_loss":   round(val_loss, 5),
            "val_acc":    round(val_acc, 4),
            "lr":         lr_now,
        })

        # Save last checkpoint (always)
        torch.save(model.state_dict(),
                   os.path.join(args.checkpoint_dir, "last_model_phase2.pth"))

        # Save best checkpoint (by validation accuracy)
        if val_acc > best_val_acc:
            best_val_acc = val_acc
            epochs_no_improve = 0
            best_ckpt = os.path.join(args.checkpoint_dir, "best_model_phase2.pth")
            torch.save(model.state_dict(), best_ckpt)
            print(f"  --> New best val_acc={val_acc:.4f}. Saved: {best_ckpt}")
        else:
            epochs_no_improve += 1
            print(f"  --> No improvement for {epochs_no_improve} epoch(s).")

        # Save history every epoch
        with open(os.path.join(args.checkpoint_dir, "history.json"), "w") as f:
            json.dump(history, f, indent=2)

        # Early stopping
        if epochs_no_improve >= args.patience:
            print(f"\n[!] EARLY STOPPING at epoch {epoch}  "
                  f"(best val_acc={best_val_acc:.4f})")
            break

    print(f"\nTraining complete. Best val_acc: {best_val_acc:.4f}")
    print(f"Best model: {os.path.join(args.checkpoint_dir, 'best_model_phase2.pth')}")


